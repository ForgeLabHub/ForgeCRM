// handleCreateExport streams an export directly.
//
// Streaming avoids materialising the whole result set, and the query is scoped by
// organization and permission exactly like a list request.
func (s *Server) handleCreateExport(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	var req createExportRequest
	if err := decodeBody(w, r, &req); err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	switch req.Format {
	case "", "csv", "jsonl":
	default:
		httpx.WriteError(w, r, httpx.ValidationError(map[string]string{
			"format": "must be csv or jsonl"}))
		return
	}
	// Exporting requires the export permission for the entity, which the route
	// middleware has already checked for exports.execute; here we additionally
	// require read access to the entity being exported.
	if !s.canReadEntity(p, req.EntityType) {
		httpx.WriteError(w, r, httpx.NewError(403, httpx.CodeForbidden,
			"you do not have permission to read this entity type"))
		return
	}

	format := req.Format
	if format == "" {
		format = "csv"
	}
	filename := fmt.Sprintf("%s-%d.%s", req.EntityType, time.Now().Unix(), format)
	w.Header().Set("Content-Type", contentTypeForExport(format))
	w.Header().Set("Content-Disposition", "attachment; filename="+strconv.Quote(filename))

	_ = s.deps.Audit.Record(r.Context(), auditEntryExport(p, req.EntityType, format))

	if format == "jsonl" {
		err := s.streamJSONLExport(w, r, p, req.EntityType)
		if err != nil {
			s.deps.Log.Warn("export failed", "entity_type", req.EntityType, "error", err)
		}
		return
	}
	if err := s.streamCSVExport(w, r, p, req.EntityType); err != nil {
		s.deps.Log.Warn("export failed", "entity_type", req.EntityType, "error", err)
	}
}

func contentTypeForExport(format string) string {
	if format == "jsonl" {
		return "application/x-ndjson; charset=utf-8"
	}
	return "text/csv; charset=utf-8"
}

func (s *Server) canReadEntity(p *rbac.Principal, entity string) bool {
	switch entity {
	case "account":
		return p.Has(rbac.PermAccountsRead)
	case "contact":
		return p.Has(rbac.PermContactsRead)
	case "lead":
		return p.Has(rbac.PermLeadsRead)
	case "deal":
		return p.Has(rbac.PermDealsRead)
	case "task":
		return p.Has(rbac.PermTasksRead)
	case "ticket":
		return p.Has(rbac.PermTicketsRead)
	case "activity":
		return p.Has(rbac.PermActivitiesRead)
	}
	return false
}
