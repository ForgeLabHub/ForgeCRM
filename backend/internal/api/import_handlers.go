// handleExecuteImport queues the import and returns the job identifier
// immediately, rather than holding the request open for the whole run.
func (s *Server) handleExecuteImport(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	id, ok := pathUUID(w, r, "id")
	if !ok {
		return
	}
	var body importRequest
	if err := decodeBody(w, r, &body); err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	opts, err := importOptionsFrom(r, &body)
	if err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	job, err := s.deps.Imports.Execute(r.Context(), p, id, body.Mapping, opts)
	if err != nil {
		s.respondDomainError(w, r, err)
		return
	}
	httpx.WriteJSONStatus(w, http.StatusAccepted, map[string]any{
		"import_id": id,
		"job_id":    job.ID,
		"status":    job.Status,
		"note":      "the import runs in the background; poll /imports/{id} for progress",
	})
}

