// importOptionsFrom decodes the shared options payload.
func importOptionsFrom(r *http.Request, body *importRequest) (importx.Options, error) {
	opts := importx.Options{
		Duplicates:        body.Options.Duplicates,
		DuplicateKey:      body.Options.DuplicateKey,
		ExternalSource:    body.Options.ExternalSource,
		Delimiter:         body.Options.Delimiter,
		HasHeader:         body.Options.HasHeader,
		SheetName:         body.Options.SheetName,
		XMLRowElement:     body.Options.XMLRowElement,
		SkipRows:          body.Options.SkipRows,
		MaxRows:           body.Options.MaxRows,
		ArchiveEntry:      body.Options.ArchiveEntry,
		DefaultPipelineID: nil,
		DefaultStageID:    nil,
		DefaultOwnerID:    nil,
	}
	if body.Options.DefaultPipelineID != "" {
		id, ok := parseUUID(body.Options.DefaultPipelineID)
		if !ok {
			return opts, httpx.ValidationError(map[string]string{"default_pipeline_id": "must be a UUID"})
		}
		opts.DefaultPipelineID = &id
	}
	if body.Options.DefaultStageID != "" {
		id, ok := parseUUID(body.Options.DefaultStageID)
		if !ok {
			return opts, httpx.ValidationError(map[string]string{"default_stage_id": "must be a UUID"})
		}
		opts.DefaultStageID = &id
	}
	if body.Options.DefaultOwnerID != "" {
		id, ok := parseUUID(body.Options.DefaultOwnerID)
		if !ok {
			return opts, httpx.ValidationError(map[string]string{"default_owner_id": "must be a UUID"})
		}
		opts.DefaultOwnerID = &id
	}
	return opts, nil
}

// importRequest is the shared body for analyze, validate, dry-run and execute.
type importRequest struct {
	Mapping []importx.MappingEntry `json:"mapping"`
	Options struct {
		Duplicates        string   `json:"duplicates"`
		DuplicateKey      []string `json:"duplicate_key"`
		ExternalSource    string   `json:"external_source"`
		Delimiter         string   `json:"delimiter"`
		HasHeader         *bool    `json:"has_header"`
		SheetName         string   `json:"sheet_name"`
		XMLRowElement     string   `json:"xml_row_element"`
		DefaultOwnerID    string   `json:"default_owner_id"`
		DefaultPipelineID string   `json:"default_pipeline_id"`
		DefaultStageID    string   `json:"default_stage_id"`
		SkipRows          int64    `json:"skip_rows"`
		MaxRows           int64    `json:"max_rows"`
		ArchiveEntry      string   `json:"archive_entry"`
	} `json:"options"`
}

func (s *Server) handleAnalyzeImport(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	id, ok := pathUUID(w, r, "id")
	if !ok {
		return
	}
	var body importRequest
	if r.ContentLength > 0 {
		if err := decodeBody(w, r, &body); err != nil {
			httpx.WriteError(w, r, err)
			return
		}
	}
	opts, err := importOptionsFrom(r, &body)
	if err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	result, err := s.deps.Imports.Analyze(r.Context(), p, id, opts)
	if err != nil {
		s.respondDomainError(w, r, err)
		return
	}
	httpx.WriteJSON(w, result)
}

