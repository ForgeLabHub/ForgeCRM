func (s *Server) handleImportFields(w http.ResponseWriter, r *http.Request) {
	entity := r.URL.Query().Get("entity_type")
	if entity == "" {
		httpx.WriteError(w, r, httpx.ValidationError(map[string]string{"entity_type": "is required"}))
		return
	}
	fields := importx.FieldList(entity)
	if fields == nil {
		httpx.WriteError(w, r, httpx.ValidationError(map[string]string{"entity_type": "unsupported entity type"}))
		return
	}
	httpx.WriteJSON(w, map[string]any{"entity_type": entity, "fields": fields})
}

