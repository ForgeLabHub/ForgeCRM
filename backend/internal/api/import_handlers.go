// mountImports registers the Data Import Center routes.
func (s *Server) mountImports(r chi.Router) {
	r.Route("/imports", func(r chi.Router) {
		r.With(s.perm(rbac.PermImportsRead)).Get("/", s.handleListImports)
		r.With(s.perm(rbac.PermImportsCreate)).Post("/", s.handleCreateImport)
		// Uploading a file for an existing job is a separate operation so that a
		// large body can be streamed without a JSON envelope.
		r.With(s.perm(rbac.PermImportsCreate)).Post("/{id}/upload", s.handleUploadImportFile)
		r.With(s.perm(rbac.PermImportsRead)).Get("/{id}", s.handleGetImport)
		r.With(s.perm(rbac.PermImportsRead)).Post("/{id}/analyze", s.handleAnalyzeImport)
		r.With(s.perm(rbac.PermImportsRead)).Get("/{id}/preview", s.handlePreviewImport)
		r.With(s.perm(rbac.PermImportsExecute)).Post("/{id}/validate", s.handleValidateImport)
		r.With(s.perm(rbac.PermImportsExecute)).Post("/{id}/dry-run", s.handleDryRunImport)
		r.With(s.perm(rbac.PermImportsExecute)).Post("/{id}/execute", s.handleExecuteImport)
		r.With(s.perm(rbac.PermImportsExecute)).Post("/{id}/cancel", s.handleCancelImport)
		r.With(s.perm(rbac.PermImportsRead)).Get("/{id}/errors", s.handleImportErrors)
		r.With(s.perm(rbac.PermImportsRead)).Get("/{id}/report", s.handleImportReport)
		r.With(s.perm(rbac.PermImportsRead)).Get("/fields", s.handleImportFields)
	})

	// Exports
	r.Route("/exports", func(r chi.Router) {
		r.With(s.perm(rbac.PermExportsExecute)).Post("/", s.handleCreateExport)
	})
}

func (s *Server) handleListImports(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	pg := httpx.ParsePagination(r)
	items, total, err := s.deps.Imports.List(r.Context(), p, pg.Limit, pg.Offset)
	if err != nil {
		s.respondDomainError(w, r, err)
		return
	}
	httpx.WriteJSON(w, httpx.NewListResponse(items, total, pg))
}

type createImportRequest struct {
	Name             string `json:"name"`
	EntityType       string `json:"entity_type"`
	OriginalFilename string `json:"original_filename"`
}

// handleCreateImport creates an import job record. The file itself is uploaded in
// a following multipart request, so that a failure to create the record does not
// waste an upload and vice versa.
func (s *Server) handleCreateImport(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	var req createImportRequest
	if err := decodeBody(w, r, &req); err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	job, err := s.deps.Imports.Create(r.Context(), p, importx.CreateRequest{
		Name:             req.Name,
		EntityType:       req.EntityType,
		SourceType:       "file",
		OriginalFilename: req.OriginalFilename,
		SizeBytes:        0,
		Content:          strings.NewReader(""),
	})
	if err != nil {
		s.respondDomainError(w, r, err)
		return
	}
	httpx.WriteJSONStatus(w, http.StatusCreated, job)
}

// handleUploadImportFile accepts the file for an import job.
//
// The body is streamed to private storage; the multipart part is never buffered
// whole in memory, so a large file cannot exhaust the process.
func (s *Server) handleUploadImportFile(w http.ResponseWriter, r *http.Request) {
	p, ok := s.mustPrincipal(w, r)
	if !ok {
		return
	}
	id, ok := pathUUID(w, r, "id")
	if !ok {
		return
	}

	// Enforce the upload limit before reading a single byte.
	if r.ContentLength > s.deps.Config.ImportMaxUploadBytes {
		httpx.WriteError(w, r, httpx.NewError(413, httpx.CodePayloadTooLarge, fmt.Sprintf(
			"upload exceeds the maximum of %d bytes", s.deps.Config.ImportMaxUploadBytes)))
		return
	}
	r.Body = http.MaxBytesReader(w, r.Body, s.deps.Config.ImportMaxUploadBytes)

	reader, err := r.MultipartReader()
	if err != nil {
		httpx.WriteError(w, r, httpx.ValidationError(map[string]string{
			"file": "the request must be multipart/form-data with a file part"}))
		return
	}

	var (
		filename string
		size     int64
	)
	for {
		part, err := reader.NextPart()
		if err != nil {
			break
		}
		if part.FormName() != "file" {
			continue
		}
		filename = part.FileName()
		// The stored name is generated by the service; the client filename is
		// metadata only, so a path traversal in it cannot affect storage.
		job, err := s.deps.Imports.ReplaceFile(r.Context(), p, id, filename, part)
		if err != nil {
			s.respondDomainError(w, r, err)
			return
		}
		size = derefInt64Or(job.SizeBytes, 0)
		httpx.WriteJSONStatus(w, http.StatusCreated, map[string]any{
			"id": job.ID, "checksum_sha256": job.ChecksumSHA256, "size_bytes": size,
		})
		return
	}
	httpx.WriteError(w, r, httpx.ValidationError(map[string]string{"file": "no file part was found in the request"}))
}

