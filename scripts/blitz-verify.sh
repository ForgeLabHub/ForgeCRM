#!/usr/bin/env bash
#
# Reproduce the blitz.cloud deployment locally against a clean database.
#
# blitz.cloud builds the repository-root Dockerfile, runs the compose `api` part
# and injects DATABASE_URL. This script does the same — same image, same
# entrypoint, same one-container-serves-API-and-UI shape — and, because the
# production configuration requires HTTPS and a Secure session cookie, it puts a
# real TLS reverse proxy in front, exactly as the platform does. It then walks
# the whole path a fresh deployment takes:
#
#   clean database -> migrations (twice) -> first administrator (twice) ->
#   sign in -> /me -> sign out -> sign in again -> wrong password ->
#   liveness vs readiness with the schema removed.
#
# It is a real check, not a mock: the container is the built artefact, the
# database is a real PostgreSQL 17, and TLS is real. Nothing is asserted from a
# unit test.
#
#   ./scripts/blitz-verify.sh [image-tag]
#
# The image defaults to forgecrm-blitz-verify:latest; build it with:
#   docker build --build-arg VERSION=verify --build-arg COMMIT=$(git rev-parse --short HEAD) \
#     -t forgecrm-blitz-verify:latest .
#
# Exit code is non-zero if any check fails, so a release step can gate on it.
set -uo pipefail

image="${1:-forgecrm-blitz-verify:latest}"
run_id="blitzverify-$$"
network="${run_id}-net"
pg="${run_id}-pg"
api="${run_id}-api"
proxy="${run_id}-proxy"
https_port="${FORGECRM_BLITZ_VERIFY_PORT:-18443}"
base="https://localhost:${https_port}"
workdir="$(mktemp -d)"

# Throwaway values for a throwaway database. The secret key is long enough for
# the production minimum; the passwords are deliberately non-real and are never
# printed by this script or by the product.
secret_key="verify-only-secret-key-not-used-anywhere-0000000000000000"
admin_email="owner@forgecrm.test"
admin_password="Verify-Owner-Passw0rd-2026!"
wrong_password="definitely-not-the-password-000"

pass=0
fail=0
check() {
  local name="$1" expected="$2" actual="$3"
  if [[ "${actual}" == "${expected}" ]]; then
    printf '  \033[32mok\033[0m    %s (%s)\n' "${name}" "${actual}"
    pass=$((pass + 1))
  else
    printf '  \033[31mfail\033[0m  %s (got %s, want %s)\n' "${name}" "${actual}" "${expected}"
    fail=$((fail + 1))
  fi
}

cleanup() {
  docker rm -f "${proxy}" "${api}" "${pg}" >/dev/null 2>&1
  docker network rm "${network}" >/dev/null 2>&1
  rm -rf "${workdir}"
}
trap cleanup EXIT

if ! docker image inspect "${image}" >/dev/null 2>&1; then
  echo "error: image ${image} not found. Build it first (see the header)." >&2
  exit 2
fi

# curl against the self-signed certificate, resolved to the published port.
# `-k` is correct here: the certificate is generated by this script for this run.
c() { curl -sk --resolve "localhost:${https_port}:127.0.0.1" "$@"; }
code() { c -o /dev/null -w '%{http_code}' "$@"; }

echo "ForgeCRM blitz.cloud verification"
echo "  image:   ${image}"
echo "  network: ${network}"
echo "  url:     ${base}"
echo

# --- TLS material, as a platform terminates TLS in front of the container ----
openssl req -x509 -newkey rsa:2048 -nodes -days 1 \
  -keyout "${workdir}/key.pem" -out "${workdir}/cert.pem" \
  -subj "/CN=localhost" -addext "subjectAltName=DNS:localhost" >/dev/null 2>&1
cat > "${workdir}/nginx.conf" <<'NGINX'
events {}
http {
  server {
    listen 8443 ssl;
    server_name localhost;
    ssl_certificate     /etc/nginx/cert.pem;
    ssl_certificate_key /etc/nginx/key.pem;
    client_max_body_size 256m;
    location / {
      proxy_pass http://api:8080;
      proxy_http_version 1.1;
      proxy_set_header Host              $host;
      proxy_set_header X-Real-IP         $remote_addr;
      proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
      proxy_set_header X-Forwarded-Proto https;
      proxy_set_header Connection        "";
    }
  }
}
NGINX

docker network create "${network}" >/dev/null
# Read the subnet Docker actually assigned, so the trusted-proxy CIDR is a real
# value rather than a guess, and a busy CI host cannot collide with a fixed one.
subnet="$(docker network inspect "${network}" \
  -f '{{range .IPAM.Config}}{{.Subnet}}{{end}}')"

# --- 1. A clean PostgreSQL 17, as the managed database is -------------------
echo "Clean database"
docker run -d --name "${pg}" --network "${network}" \
  -e POSTGRES_USER=forgecrm -e POSTGRES_PASSWORD=forgecrm -e POSTGRES_DB=forgecrm \
  postgres:17-alpine >/dev/null
# Readiness is probed over TCP, not the unix socket. The image's entrypoint runs
# a temporary server on the socket while it initialises the cluster, so a
# socket-only probe reports ready a second before the real server exists; the
# API reaches the database over TCP, so that is the connection that must work.
for i in $(seq 1 60); do
  docker exec "${pg}" pg_isready -h 127.0.0.1 -U forgecrm -d forgecrm >/dev/null 2>&1 && break
  sleep 1
done
check "PostgreSQL accepts connections" "0" \
  "$(docker exec "${pg}" psql -h 127.0.0.1 -U forgecrm -d forgecrm -tAc 'select 1' >/dev/null 2>&1; echo $?)"

# The production environment blitz.cloud injects, minus PORT (we fix the listen
# address). FORGECRM_TRUSTED_PROXIES is the real CIDR of the proxy network, not
# a wildcard, so the client address is read from the forwarding header.
prod_env=(
  -e "DATABASE_URL=postgres://forgecrm:forgecrm@${pg}:5432/forgecrm?sslmode=disable"
  -e "FORGECRM_ENV=production"
  -e "FORGECRM_SECRET_KEY=${secret_key}"
  -e "FORGECRM_BASE_URL=${base}"
  -e "FORGECRM_COOKIE_SECURE=true"
  -e "FORGECRM_TRUSTED_PROXIES=${subnet}"
)

# --- 2. Migrations are a separate, repeatable step --------------------------
echo
echo "Migrations (separate deploy step)"
docker run --rm --network "${network}" "${prod_env[@]}" "${image}" -migrate >"${workdir}/migrate1.log" 2>&1
check "first -migrate succeeds" "0" "$?"
docker run --rm --network "${network}" "${prod_env[@]}" "${image}" -migrate >"${workdir}/migrate2.log" 2>&1
check "second -migrate is a no-op (safe re-run)" "0" "$?"

# The exact table whose absence produced `relation "users" does not exist` must
# now exist: this is the failure the whole task turns on.
users_exists="$(docker exec "${pg}" psql -U forgecrm -d forgecrm -tAc \
  "SELECT to_regclass('public.users') IS NOT NULL" 2>/dev/null | tr -d '[:space:]')"
check "table users exists after migrate" "t" "${users_exists}"

# --- 3. The first administrator is created by an explicit command -----------
echo
echo "First administrator (bootstrap)"
docker run --rm --network "${network}" "${prod_env[@]}" \
  -e "FORGECRM_BOOTSTRAP_PASSWORD=${admin_password}" \
  "${image}" -bootstrap-admin -bootstrap-email "${admin_email}" >"${workdir}/bootstrap.log" 2>&1
check "bootstrap-admin succeeds" "0" "$?"
if grep -qF "${admin_password}" "${workdir}/bootstrap.log"; then
  check "bootstrap output does not contain the password" "absent" "present"
else
  check "bootstrap output does not contain the password" "absent" "absent"
fi
# Re-running with a different password must not overwrite the existing owner.
docker run --rm --network "${network}" "${prod_env[@]}" \
  -e "FORGECRM_BOOTSTRAP_PASSWORD=${wrong_password}" \
  "${image}" -bootstrap-admin -bootstrap-email "${admin_email}" >"${workdir}/bootstrap2.log" 2>&1
check "second bootstrap is a no-op (does not overwrite)" "0" "$?"

# --- 4. Start the API and the TLS proxy, the way the platform does ----------
echo
echo "API startup"
docker run -d --name "${api}" --network "${network}" --network-alias api \
  "${prod_env[@]}" \
  -e "FORGECRM_HTTP_ADDR=:8080" -e "FORGECRM_STATIC_DIR=/app/public" \
  "${image}" >/dev/null
docker run -d --name "${proxy}" --network "${network}" \
  -v "${workdir}/nginx.conf:/etc/nginx/nginx.conf:ro" \
  -v "${workdir}/cert.pem:/etc/nginx/cert.pem:ro" \
  -v "${workdir}/key.pem:/etc/nginx/key.pem:ro" \
  -p "127.0.0.1:${https_port}:8443" nginx:1.27-alpine >/dev/null

ready=1
for i in $(seq 1 60); do
  if [[ "$(code "${base}/ready")" == "200" ]]; then ready=0; break; fi
  sleep 1
done
if [[ "${ready}" -ne 0 ]]; then
  echo "  API did not become ready; last API log lines:"
  docker logs "${api}" 2>&1 | tail -20 | sed 's/^/    /'
fi
check "GET /ready" "200" "$(code "${base}/ready")"
check "GET /health" "200" "$(code "${base}/health")"
# Build metadata reaches the running process: not the "dev"/"unknown" placeholder.
health_body="$(c "${base}/health")"
check "health reports a real version" "yes" \
  "$(printf '%s' "${health_body}" | grep -qE '"version":"[^"]+"' && ! printf '%s' "${health_body}" | grep -q '"version":"dev"' && echo yes || echo no)"

# The SPA is served at the root, not a JSON 404.
root_ct="$(c -o /dev/null -w '%{content_type}' "${base}/")"
case "${root_ct}" in
  text/html*) check "GET / serves the web interface (html)" "html" "html" ;;
  *) check "GET / serves the web interface (html)" "html" "${root_ct}" ;;
esac
api404_ct="$(c -o /dev/null -w '%{content_type}' "${base}/api/v1/does-not-exist")"
case "${api404_ct}" in
  application/json*) check "unknown /api path stays JSON" "json" "json" ;;
  *) check "unknown /api path stays JSON" "json" "${api404_ct}" ;;
esac

# --- 5. Full authentication round trip --------------------------------------
echo
echo "Authentication"
jar="$(mktemp)"

login() {
  c -c "${jar}" -X POST "${base}/api/v1/auth/login" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"$1\",\"password\":\"$2\"}"
}

body="$(login "${admin_email}" "${admin_password}")"
csrf="$(printf '%s' "${body}" | sed -n 's/.*"csrf_token":"\([^"]*\)".*/\1/p')"
check "sign in returns a CSRF token" "yes" "$([[ -n "${csrf}" ]] && echo yes || echo no)"
check "GET /api/v1/auth/me after sign in" "200" \
  "$(c -o /dev/null -w '%{http_code}' -b "${jar}" "${base}/api/v1/auth/me")"
me_email="$(c -b "${jar}" "${base}/api/v1/auth/me" | sed -n 's/.*"email":"\([^"]*\)".*/\1/p')"
check "/me reports the signed-in owner" "${admin_email}" "${me_email}"

check "POST /api/v1/auth/logout" "200" \
  "$(c -o /dev/null -w '%{http_code}' -b "${jar}" -X POST "${base}/api/v1/auth/logout" -H "X-CSRF-Token: ${csrf}")"
check "GET /api/v1/auth/me after logout" "401" \
  "$(c -o /dev/null -w '%{http_code}' -b "${jar}" "${base}/api/v1/auth/me")"

body="$(login "${admin_email}" "${admin_password}")"
csrf2="$(printf '%s' "${body}" | sed -n 's/.*"csrf_token":"\([^"]*\)".*/\1/p')"
check "sign in again succeeds" "yes" "$([[ -n "${csrf2}" ]] && echo yes || echo no)"

check "wrong password is refused" "401" \
  "$(c -o /dev/null -w '%{http_code}' -X POST "${base}/api/v1/auth/login" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"${admin_email}\",\"password\":\"${wrong_password}\"}")"

check "unauthenticated CRM write is refused" "401" \
  "$(c -o /dev/null -w '%{http_code}' -X POST "${base}/api/v1/contacts" \
    -H 'Content-Type: application/json' -d '{}')"
rm -f "${jar}"

# --- 6. The probe distinguishes "process up" from "schema ready" ------------
echo
echo "Readiness is not liveness"
# Drop the schema under the running API: /health must stay 200 (the process is
# alive) while /ready must become 503 (the schema is gone). This is the exact
# distinction that hid `relation "users" does not exist` behind a green probe.
docker exec "${pg}" psql -U forgecrm -d forgecrm -c "DROP SCHEMA public CASCADE; CREATE SCHEMA public;" >/dev/null 2>&1
check "GET /health with the schema dropped (still alive)" "200" "$(code "${base}/health")"
check "GET /ready with the schema dropped (not ready)" "503" "$(code "${base}/ready")"
login_status="$(c -o /dev/null -w '%{http_code}' -X POST "${base}/api/v1/auth/login" \
  -H 'Content-Type: application/json' -d "{\"email\":\"${admin_email}\",\"password\":\"${admin_password}\"}")"
check "login against a broken schema is 5xx, not 200" "5xx" \
  "$([[ "${login_status}" =~ ^5 ]] && echo 5xx || echo "${login_status}")"

echo
if [[ ${fail} -eq 0 ]]; then
  printf '\033[32mblitz.cloud verification passed (%d checks).\033[0m\n' "${pass}"
  exit 0
fi
printf '\033[31mblitz.cloud verification failed (%d passed, %d failed).\033[0m\n' "${pass}" "${fail}"
exit 1
