/**
 * Content for the public site.
 *
 * Everything the marketing pages render lives here as data, so a page is a
 * layout over a typed document rather than hand-written markup. That is what
 * makes the variants possible: the same service, case or tariff renders in the
 * agency layout, the catalogue layout and the media layout without a second
 * copy drifting away from the first.
 *
 * Prices and phone numbers are the ones the business publishes; they are not
 * placeholders. Where a figure genuinely depends on scope ("from"), the copy
 * says so instead of inventing precision.
 */

export interface Service {
  slug: string
  title: string
  group: ServiceGroupId
  summary: string
  /** What the client gets, in their words, not ours. */
  outcomes: string[]
  /** The work itself, in order, so the engagement is not a black box. */
  steps: { title: string; text: string }[]
  /** Price framing. `null` means "on request" and the UI says that. */
  from: number | null
  duration: string
  lead: string
}

